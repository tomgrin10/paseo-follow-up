import test from "node:test";
import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { readdir, readFile } from "node:fs/promises";
import { join } from "node:path";
import * as contracts from "../shared/contracts";
import { tools, actionTools, overseerTools } from "../server/mcp.mjs";
import { WAIT_TOOLS } from "../server/wait";

/**
 * The agent docs (AGENTS.md and docs/) are the map a fresh agent works from, so they must not fall behind the code.
 * Every RPC, every agent tool and every source file has to be named there (in backticks), and every path or npm
 * script the docs name has to exist. Add a line to the right doc when this fails; exempt only with a reason.
 */
const EXEMPT: Record<string, string> = {
  // Generated by scripts/build.mjs; the docs name their sources instead.
  "server/mcp-source.ts": "generated from server/mcp.mjs",
  "server/hook-source.ts": "generated from server/agent-hook.mjs",
  "server/overseer-prompt-source.ts": "generated from server/overseer-prompt.md",
  "server/wait-runner-source.ts": "generated from server/wait-runner.sh",
  "server/mcp.d.mts": "type declarations for server/mcp.mjs",
  "server/update-watchdog-source.ts": "generated from server/update-watchdog.mjs",
  "server/update-watchdog.d.mts": "type declarations for server/update-watchdog.mjs",
};

async function corpus(): Promise<string> {
  const docs = (await readdir("docs")).filter(f => f.endsWith(".md")).map(f => join("docs", f));
  return (await Promise.all(["AGENTS.md", ...docs].map(f => readFile(f, "utf8")))).join("\n");
}
const named = (text: string, name: string) => text.includes("`" + name + "`") || new RegExp("`[^`\\n]*\\b" + name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\b[^`\\n]*`").test(text);

test("docs: every RPC in shared/contracts.ts is named in AGENTS.md or docs/", async () => {
  const text = await corpus();
  const rpcs = Object.values(contracts).map(c => (c as { name?: unknown })?.name).filter((n): n is string => typeof n === "string" && n.startsWith("follow."));
  assert.ok(rpcs.length > 50, "found the RPC contracts");
  const missing = rpcs.filter(r => !EXEMPT[r] && !text.includes("`" + r + "`"));
  assert.deepEqual(missing, [], `RPCs missing from the docs (add them to docs/rpcs-and-tools.md): ${missing.join(", ")}`);
});

test("docs: every agent tool is named in AGENTS.md or docs/", async () => {
  const text = await corpus();
  const names = [...tools, ...actionTools, ...overseerTools].map((t: unknown[]) => t[0] as string).concat(WAIT_TOOLS);
  assert.ok(names.length > 70, "found the tool lists");
  const missing = names.filter(n => !EXEMPT[n] && !text.includes("`" + n + "`"));
  assert.deepEqual(missing, [], `Agent tools missing from the docs (add them to docs/rpcs-and-tools.md): ${missing.join(", ")}`);
});

test("docs: every source file and script is in the file index", async () => {
  const text = await corpus();
  const files: string[] = ["index.server.ts", "index.client.tsx"];
  for (const dir of ["server", "shared", "client", "scripts"]) for (const f of await readdir(dir)) if (/\.(ts|tsx|mjs|cjs|sh|md)$/.test(f)) files.push(`${dir}/${f}`);
  const missing = files.filter(f => !EXEMPT[f] && !named(text, f));
  assert.deepEqual(missing, [], `Files missing from AGENTS.md or docs/ (add them to the file index or a subsystem doc): ${missing.join(", ")}`);
});

test("docs: every path and npm script the docs name exists", async () => {
  const text = await corpus();
  const paths = new Set([...text.matchAll(/`((?:server|shared|client|scripts|tests|changes|docs|\.github)\/[\w./-]+\.\w+)`/g)].map(m => m[1]));
  const gone = [...paths].filter(p => !existsSync(p));
  assert.deepEqual(gone, [], `The docs name files that don't exist: ${gone.join(", ")}`);
  const scripts = Object.keys(JSON.parse(await readFile("package.json", "utf8")).scripts);
  const named = new Set([...text.matchAll(/npm run ([\w:-]+)/g)].map(m => m[1]));
  const unknown = [...named].filter(s => !scripts.includes(s));
  assert.deepEqual(unknown, [], `The docs name npm scripts that don't exist: ${unknown.join(", ")}`);
});
